// Serialization format versions.
const (
	// Version1 is the legacy format: integer node ids, implicit root (id 0),
	// sibling order stored per node.
	Version1 = 1
	// Version2 is the current format: string ids, explicit root with empty
	// parentId, explicit ordered children lists.
	Version2 = 2

	// CurrentVersion is the format written by Save.
	CurrentVersion = Version2
)

// Serialization errors.
var (
	// ErrCorruptData is returned when the input is not valid scene data.
	ErrCorruptData = errors.New("scene: corrupt serialized data")
	// ErrUnsupportedVersion is returned when the data uses a format version
	// this build cannot read.
	ErrUnsupportedVersion = errors.New("scene: unsupported serialization version")
)

// transformData is the JSON representation of a local transform.
type transformData struct {
	Position [3]float64 `json:"position"`
	Rotation [4]float64 `json:"rotation"` // x, y, z, w
	Scale    [3]float64 `json:"scale"`
}

// sceneFileV2 is the current on-disk format.
type sceneFileV2 struct {
	Version int                `json:"version"`
	Nodes   []serializedNodeV2 `json:"nodes"`
}

type serializedNodeV2 struct {
	ID       string        `json:"id"`
	Name     string        `json:"name"`
	ParentID string        `json:"parentId"`
	Children []string      `json:"children"`
	Local    transformData `json:"local"`
}

// sceneFileV1 is the legacy on-disk format.
type sceneFileV1 struct {
	Version int                `json:"version"`
	Nodes   []serializedNodeV1 `json:"nodes"`
}

type serializedNodeV1 struct {
	ID       int64         `json:"id"`
	Name     string        `json:"name"`
	ParentID int64         `json:"parentId"` // 0 denotes the root
	Order    int           `json:"order"`
	Local    transformData `json:"local"`
}

// Save writes the scene in the current format (Version2). Nodes are emitted
// breadth-first from the root, so the output is deterministic for a given
// tree state.
func (s *Scene) Save(w io.Writer) error {
	s.mu.RLock()
	defer s.mu.RUnlock()

	if _, ok := s.nodes[s.root]; !ok {
		return ErrNodeNotFound
	}
	file := sceneFileV2{Version: CurrentVersion}
	queue := []NodeID{s.root}
	for len(queue) > 0 {
		id := queue[0]
		queue = queue[1:]
		n := s.nodes[id]
		file.Nodes = append(file.Nodes, serializedNodeV2{
			ID:       string(id),
			Name:     n.name,
			ParentID: string(n.parent),
			Children: idsToStrings(n.children),
			Local:    transformToData(n.local),
		})
		queue = append(queue, n.children...)
	}
	enc := json.NewEncoder(w)
	enc.SetIndent("", "  ")
	if err := enc.Encode(file); err != nil {
		return fmt.Errorf("scene: encode failed: %w", err)
	}
	return nil
}

// SaveV1 writes the scene in the legacy Version1 format. It exists for
// cross-version compatibility testing; new data should use Save.
func (s *Scene) SaveV1(w io.Writer) error {
	s.mu.RLock()
	defer s.mu.RUnlock()

	if _, ok := s.nodes[s.root]; !ok {
		return ErrNodeNotFound
	}
	file := sceneFileV1{Version: Version1}
	// Emit nodes breadth-first; assign the root id 0 and derive the per-node
	// sibling order from the parent's children list position.
	queue := []NodeID{s.root}
	order := map[NodeID]int{}
	for len(queue) > 0 {
		id := queue[0]
		queue = queue[1:]
		n := s.nodes[id]
		// Sibling order: index among parent's children.
		sibOrder := 0
		if n.parent != "" {
			siblings := s.nodes[n.parent].children
			sibOrder = indexOf(siblings, id)
		}
		order[id] = sibOrder
		var pid int64
		if id != s.root {
			pid = nodeIDToV1(n.parent)
		}
		file.Nodes = append(file.Nodes, serializedNodeV1{
			ID:       nodeIDToV1(id),
			Name:     n.name,
			ParentID: pid,
			Order:    sibOrder,
			Local:    transformToData(n.local),
		})
		queue = append(queue, n.children...)
	}
	enc := json.NewEncoder(w)
	enc.SetIndent("", "  ")
	if err := enc.Encode(file); err != nil {
		return fmt.Errorf("scene: encode failed: %w", err)
	}
	return nil
}

// nodeIDToV1 maps a current string node id to a legacy integer id. The root
// maps to 0; other ids are parsed from their "n<digits>" form.
func nodeIDToV1(id NodeID) int64 {
	if id == rootID {
		return 0
	}
	n, err := strconv.ParseInt(strings.TrimPrefix(string(id), "n"), 10, 64)
	if err != nil {
		// ids generated by this build are "n1", "n2", ...; fall back to a
		// stable hash-like value for safety.
		var h int64
		for _, b := range []byte(id) {
			h = h*31 + int64(b)
		}
		if h < 0 {
			h = -h
		}
		if h == 0 {
			h = 1
		}
		return h
	}
	return n
}

// Load reads scene data in any supported version, migrating older formats
// forward, validating the structure (rejecting cycles and references to
// deleted parents) and returning a ready-to-use scene.
func Load(r io.Reader) (*Scene, error) {
	raw, err := io.ReadAll(r)
	if err != nil {
		return nil, fmt.Errorf("scene: read failed: %w", err)
	}
	// Peek at the version field without committing to a struct.
	var head struct {
		Version int `json:"version"`
	}
	if err := json.Unmarshal(raw, &head); err != nil {
		return nil, fmt.Errorf("%w: %v", ErrCorruptData, err)
	}
	switch head.Version {
	case Version1:
		var f sceneFileV1
		if err := json.Unmarshal(raw, &f); err != nil {
			return nil, fmt.Errorf("%w: %v", ErrCorruptData, err)
		}
		return loadV1(f)
	case Version2:
		var f sceneFileV2
		if err := json.Unmarshal(raw, &f); err != nil {
			return nil, fmt.Errorf("%w: %v", ErrCorruptData, err)
		}
		return loadV2(f)
	default:
		return nil, fmt.Errorf("%w: %d", ErrUnsupportedVersion, head.Version)
	}
}

// loadV2 builds a scene from current-format data after validating it.
func loadV2(f sceneFileV2) (*Scene, error) {
	if f.Version != Version2 {
		return nil, fmt.Errorf("%w: expected version %d", ErrCorruptData, Version2)
	}
	if len(f.Nodes) == 0 {
		return nil, fmt.Errorf("%w: no nodes", ErrCorruptData)
	}

	// Index nodes by id.
	byID := make(map[string]serializedNodeV2, len(f.Nodes))
	for _, n := range f.Nodes {
		if n.ID == "" {
			return nil, fmt.Errorf("%w: node with empty id", ErrCorruptData)
		}
		if _, exists := byID[n.ID]; exists {
			return nil, fmt.Errorf("%w: duplicate node id %q", ErrCorruptData, n.ID)
		}
		byID[n.ID] = n
	}

	// Exactly one root (empty parentId).
	var rootIDStr string
	for _, n := range f.Nodes {
		if n.ParentID == "" {
			if rootIDStr != "" {
				return nil, fmt.Errorf("%w: multiple root nodes", ErrCorruptData)
			}
			rootIDStr = n.ID
		}
	}
	if rootIDStr == "" {
		return nil, fmt.Errorf("%w: no root node", ErrCorruptData)
	}

	// Validate parent references and children consistency.
	seenChild := map[string]bool{}
	for _, n := range f.Nodes {
		if n.ID != rootIDStr {
			if _, ok := byID[n.ParentID]; !ok {
				return nil, fmt.Errorf("%w: node %q references missing parent %q", ErrCorruptData, n.ID, n.ParentID)
			}
		}
		for _, cid := range n.Children {
			child, ok := byID[cid]
			if !ok {
				return nil, fmt.Errorf("%w: node %q lists missing child %q", ErrCorruptData, n.ID, cid)
			}
			if child.ParentID != n.ID {
				return nil, fmt.Errorf("%w: child %q of %q has parentId %q", ErrCorruptData, cid, n.ID, child.ParentID)
			}
			if seenChild[cid] {
				return nil, fmt.Errorf("%w: node %q listed as child of multiple parents", ErrCorruptData, cid)
			}
			seenChild[cid] = true
		}
	}
	// Every non-root node must appear exactly once as a child.
	for _, n := range f.Nodes {
		if n.ID == rootIDStr {
			continue
		}
		if !seenChild[n.ID] {
			return nil, fmt.Errorf("%w: node %q is not reachable from root", ErrCorruptData, n.ID)
		}
	}
	// Cycle detection via parent-chain walk.
	for _, n := range f.Nodes {
		seen := map[string]bool{n.ID: true}
		cur := n.ParentID
		for cur != "" {
			if seen[cur] {
				return nil, fmt.Errorf("%w: involving node %q", ErrCorruptData, n.ID)
			}
			seen[cur] = true
			cur = byID[cur].ParentID
		}
	}

	// Build the scene breadth-first from the root.
	s := &Scene{
		nodes: make(map[NodeID]*Node, len(f.Nodes)),
		root:  NodeID(rootIDStr),
	}
	queue := []string{rootIDStr}
	for len(queue) > 0 {
		id := queue[0]
		queue = queue[1:]
		sn := byID[id]
		n := &Node{
			id:       NodeID(id),
			name:     sn.Name,
			parent:   NodeID(sn.ParentID),
			children: stringsToIDs(sn.Children),
			local:    sn.Local.toTransform(),
			dirty:    true,
		}
		s.nodes[NodeID(id)] = n
		queue = append(queue, sn.Children...)
	}
	// Root world is identity * local; mark it clean after first computation.
	if err := s.Validate(); err != nil {
		return nil, err
	}
	return s, nil
}

// loadV1 migrates legacy data to Version2 and delegates to loadV2.
func loadV1(f sceneFileV1) (*Scene, error) {
	if f.Version != Version1 {
		return nil, fmt.Errorf("%w: expected version %d", ErrCorruptData, Version1)
	}
	// Convert to v2 nodes. Root is id 0 with parentId 0.
	v2 := sceneFileV2{Version: Version2}
	childrenOf := map[int64][]serializedNodeV1{}
	var hasRoot bool
	for _, n := range f.Nodes {
		if n.ID == 0 {
			hasRoot = true
			if n.ParentID != 0 {
				return nil, fmt.Errorf("%w: root has non-zero parentId", ErrCorruptData)
			}
		}
		if n.ID != 0 {
			childrenOf[n.ParentID] = append(childrenOf[n.ParentID], n)
		}
	}
	if !hasRoot {
		return nil, fmt.Errorf("%w: no root node (id 0)", ErrCorruptData)
	}
	// Sort each children list by the stored sibling order.
	for pid := range childrenOf {
		sort.SliceStable(childrenOf[pid], func(i, j int) bool {
			return childrenOf[pid][i].Order < childrenOf[pid][j].Order
		})
	}
	// Emit nodes breadth-first.
	queue := []int64{0}
	emitted := map[int64]bool{}
	for len(queue) > 0 {
		id := queue[0]
		queue = queue[1:]
		if emitted[id] {
			continue
		}
		emitted[id] = true
		var sn serializedNodeV1
		found := false
		for _, n := range f.Nodes {
			if n.ID == id {
				sn = n
				found = true
				break
			}
		}
		if !found {
			return nil, fmt.Errorf("%w: missing node id %d", ErrCorruptData, id)
		}
		parentID := ""
		if id != 0 {
			parentID = strconv.FormatInt(sn.ParentID, 10)
		}
		kids := childrenOf[id]
		childIDs := make([]string, 0, len(kids))
		for _, k := range kids {
			childIDs = append(childIDs, strconv.FormatInt(k.ID, 10))
		}
		v2.Nodes = append(v2.Nodes, serializedNodeV2{
			ID:       strconv.FormatInt(id, 10),
			Name:     sn.Name,
			ParentID: parentID,
			Children: childIDs,
			Local:    sn.Local,
		})
		for _, k := range kids {
			queue = append(queue, k.ID)
		}
	}
	return loadV2(v2)
}

// --- conversion helpers ---

func transformToData(t mathx.Transform) transformData {
	return transformData{
		Position: [3]float64{t.Position.X, t.Position.Y, t.Position.Z},
		Rotation: [4]float64{t.Rotation.X, t.Rotation.Y, t.Rotation.Z, t.Rotation.W},
		Scale:    [3]float64{t.Scale.X, t.Scale.Y, t.Scale.Z},
	}
}

func (d transformData) toTransform() mathx.Transform {
	return mathx.Transform{
		Position: mathx.Vec3{X: d.Position[0], Y: d.Position[1], Z: d.Position[2]},
		Rotation: mathx.Quat{X: d.Rotation[0], Y: d.Rotation[1], Z: d.Rotation[2], W: d.Rotation[3]},
		Scale:    mathx.Vec3{X: d.Scale[0], Y: d.Scale[1], Z: d.Scale[2]},
	}
}

func idsToStrings(ids []NodeID) []string {
	out := make([]string, len(ids))
	for i, id := range ids {
		out[i] = string(id)
	}
	return out
}

func stringsToIDs(ids []string) []NodeID {
	out := make([]NodeID, len(ids))
	for i, id := range ids {
		out[i] = NodeID(id)
	}
	return out
}
